export function extractMedicationNames(message: string): string[] {
  const lower = message.toLowerCase();
  const found = new Set<string>();

  for (const med of COMMON_MEDICATIONS) {
    if (lower.includes(med)) {
      found.add(med);
    }
  }

  return Array.from(found);
}
